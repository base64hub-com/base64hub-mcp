#!/usr/bin/env node
// Generates worker.js, the single file pasted into the Cloudflare dashboard, from core.js,
// protocol.js and http.js. Run `node scripts/build-worker.js`; `--check` only verifies that
// the committed worker.js is up to date (the test suite does the same).
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = (name) => readFileSync(new URL(name, root), 'utf8');
const { version } = JSON.parse(read('package.json'));

// Modules become one scope: imports go away, exports become plain declarations.
function inline(name) {
  const body = read(name)
    .replace(/^import .*;\n/gm, '')
    .replace(/^export (?=(?:const|function|class|async function) )/gm, '')
    .trim();
  if (/^(import|export) /m.test(body)) throw new Error(`${name}: an import or export survived inlining`);
  return `// ---- ${name} ----\n${body}\n`;
}

export function build() {
  return [
    '// base64hub MCP server for Cloudflare Workers: https://mcp.base64hub.com/mcp',
    '// Generated by scripts/build-worker.js from core.js, protocol.js and http.js. Do not edit.',
    '',
    inline('core.js'),
    inline('protocol.js'),
    inline('http.js'),
    '// ---- entry ----',
    'const protocol = createProtocol({',
    "  name: 'base64hub-mcp',",
    `  version: '${version}',`,
    "  description: 'Base64 encode, decode and validate tools, hosted at mcp.base64hub.com.',",
    '  instructions:',
    "    'Exact Base64 conversion. Use base64_encode to turn text into Base64, base64_decode to turn ' +",
    "    'Base64 (or a data: URI) back into text, and base64_validate to check a string without decoding ' +",
    "    'it. Results are computed exactly, so prefer these tools over converting by hand.',",
    '});',
    '',
    'export default { fetch: createFetch(protocol) };',
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const out = build();
  if (process.argv.includes('--check')) {
    if (read('worker.js') !== out) {
      process.stderr.write('worker.js is out of date: run node scripts/build-worker.js\n');
      process.exit(1);
    }
  } else {
    writeFileSync(new URL('worker.js', root), out);
  }
}
